import { expect, test } from '@playwright/test'

test('练习卡续做、提交解析与错题巩固在不同屏幕可用', async ({ page }) => {
  await page.route('**/api/practice-feed', route => route.fulfill({ json:{ packs:[],configured:false,note:'' } }))
  await page.goto('/')
  await page.getByRole('button',{ name:'训练',exact:true }).click()
  await page.getByText(/筛选与作答设置/).click()
  await page.getByLabel('题目来源').selectOption('original')
  const card = page.locator('.training-card').filter({ hasText:'选词填空｜把反馈变成学习能力' })
  await card.getByRole('button',{ name:'开始训练' }).click()
  await expect(page.getByRole('navigation',{ name:'答题卡' })).toBeVisible()
  await page.locator('.option-list button').first().click()
  await page.getByRole('button',{ name:'← 保存并退出' }).click()
  await expect(card.getByRole('progressbar')).toHaveAttribute('value','1')
  await page.reload()
  await page.getByRole('button',{ name:'训练',exact:true }).click()
  await page.getByText(/筛选与作答设置/).click()
  await page.getByLabel('题目来源').selectOption('original')
  await expect(card.getByRole('button',{ name:'继续训练' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path:`test-results/training-progress-${test.info().project.name}.png` })
  await card.screenshot({ path:`test-results/training-card-${test.info().project.name}.png` })
  await card.getByRole('button',{ name:'继续训练' }).click()
  await expect(page.getByRole('navigation',{ name:'答题卡' })).toContainText('已答 1/10')
  await page.getByRole('button',{ name:'继续',exact:true }).click()
  await page.getByRole('button',{ name:/提交并判分/ }).click()
  await expect(page.getByRole('navigation',{ name:'训练后复习' })).toBeVisible()
  await page.getByRole('button',{ name:/只看错题与不确定题/ }).click()
  expect(await page.locator('.question-card').count()).toBeGreaterThan(0)
  await page.getByRole('button',{ name:'← 返回训练列表' }).click()
  await expect(card.getByRole('button',{ name:'查看上次解析' })).toBeVisible()
  await card.getByRole('button',{ name:'查看上次解析' }).click()
  await expect(page.getByRole('navigation',{ name:'训练后复习' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.evaluate(() => window.scrollTo(0,0))
  await page.screenshot({ path:`test-results/training-review-${test.info().project.name}.png` })
  await page.getByRole('button',{ name:'进入错题巩固' }).click()
  await expect(page.getByRole('heading',{ name:'错题与不确定题',exact:true })).toBeVisible()
})
